export type Locale = "en" | "zh";
type Messages = { [K in keyof typeof en]: string };

const dictionaries: Record<Locale, Messages> = { en, zh };
const I18nCtx = createContext<{
  t: Messages;
  lang: Locale;
  setLang: (lang: Locale) => void;
  toggleLang: () => void;
}>({
  t: zh,
  lang: "zh",
  setLang: () => {},
  toggleLang: () => {},
});

function getInitialLang(): Locale {
  const stored = window.localStorage.getItem("vibe-ui-lang");
  return stored === "en" || stored === "zh" ? stored : "zh";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Locale>(getInitialLang);
  const setLang = (next: Locale) => setLangState(next);
  const toggleLang = () => setLangState((current) => current === "zh" ? "en" : "zh");

  useEffect(() => {
    window.localStorage.setItem("vibe-ui-lang", lang);
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);

  const value = useMemo(() => ({ t: dictionaries[lang], lang, setLang, toggleLang }), [lang]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() { return useContext(I18nCtx); }
